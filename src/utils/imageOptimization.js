/**
 * Validates if a URL is from the trusted flagcdn.com domain
 * Prevents URL injection attacks by validating the full hostname
 */
function isValidFlagCdnUrl(url) {
  if (typeof url !== 'string') return false

  try {
    const urlObj = new URL(url)
    const hostname = urlObj.hostname.toLowerCase()

    // Only allow exact domain or subdomains of flagcdn.com
    return hostname === 'flagcdn.com' || hostname.endsWith('.flagcdn.com')
  } catch (_error) {
    return false
  }
}

/**
 * Generates a flag URL from FIFA country code
 * @param {string} fifaCode - FIFA country code (e.g., 'ENG', 'ESP')
 * @returns {string} - Flag URL
 */
export function getFlagUrl(fifaCode) {
  if (!fifaCode) {
    return null
  }

  // Convert FIFA code to ISO code for flagcdn.com
  const isoCode = fifaCode.toLowerCase()
  const flagUrl = `https://flagcdn.com/w80/${isoCode}.png`
  return flagUrl
}

